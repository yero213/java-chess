public class Vakje {
    private int x;
    private int y;
    private boolean bevatStuk;

    public Vakje(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }
    public int getY() {
        return y;
    }

    public boolean getBevatStuk() {
        return bevatStuk;
    }

    public void  setBevatStuk(boolean bevatStuk) {this.bevatStuk = bevatStuk;}



}
